// 印刷用のPDFの最後につける「出し方メモ」。コンビニで印刷しているあいだにサイトを閉じても、出し方が手元に残る
// やることを「□」の行に分け、終わったものに印を付けながら進められるようにする
// 文だけを組み立てる（画面の部品は使わない）ので、scripts/samples.js からも同じ文を作れる
window.SendMemo = (() => {
  const CHECK = '□　';
  const check = (t) => `${CHECK}${t}`;

  // o：{ kind: 'petition' | 'request', count: 通数（議会1つあたり）, titles: 件名の並び, figs: 送り方の図を入れるか,
  //      councils: [{ name, page, mail, denshi, tel, address, access, deadline, sessions, stamp }] }
  //      sessions：定例会の月（例：'3・6・9・12'。data/sessions.js）
  function build(o) {
    const request = o.kind === 'request';
    const doc = request ? '要望書' : '陳情書';
    const L = [
      `　　　　${doc}の出し方メモ`,
      '※このメモは手元に残すものです。出す先には送りません。終わったところの□に印を付けながら進めてください。',
      '',
      '【出すもの】',
      ...o.titles.map((t, i) => `${i + 1}．${t}`),
      `（${doc}は1通ずつ別の紙です。出す先1つにつき${o.count}通）`,
      '',
      '【1　印刷したら】',
      check(`${doc}の氏名欄に、1通ごとに手書きで署名した（押印は${request ? '任意' : '議会によって任意'}）`),
      check('空けておいた住所を、手書きで書き入れた'),
      request
        ? check('宛名の知事・市区町村長の氏名は、書き入れても空けたままでもよい')
        : check('「議長」と「様」のあいだが空いていれば、議長の氏名を書き入れた（出す直前に議会の公式サイトで確かめる）'),
      check('読み直して、個人や事件を特定できることを書いていないことを確かめた'),
    ];
    if (!request) {
      L.push(
        '',
        '【2　出し方を決める】',
        '下の「出す先ごとのこと」を見て、どれか1つに決めます。',
        check('次の定例会の開会日を、議会の公式サイトの日程で確かめた（開会日：　　月　　日）'),
        check('その3週間前（　　月　　日）までに届くように出す（締切は開会日の数日〜2週間前の議会が多く、郵送は「必着」が多い）'),
        check('電子申請ができる議会なら、電子申請で出す（紙・封筒・切手は要らない）'),
        check('住んでいる議会なら、持参すると審査される見込みがいちばん高い'),
        check('郵送する（議会によっては、審査されず議員に配るだけになる）'),
        '',
        '【3　郵送するとき】',
        ...(o.figs ? ['[[図:send]]'] : []),
        check('陳情書は1件ごとに、そのページだけを左上で1か所ホチキスで留めた（全部をまとめて留めない）'),
        check('送付状は留めずに、いちばん上に重ねた'),
        check('全部をクリアファイルに入れ、A4を折らずに角2封筒に入れた'),
        check('封筒の表に宛名を貼り（または書き）、左下に赤で「陳情書在中」と書いた'),
        check('切手を貼った（金額は下の「切手の目安」）'),
        check('封筒の裏に、自分の住所・氏名を貼り（または書き）、のりで封をした'),
        check('ポストに入れた（　　月　　日）'),
        '',
        '【3　持参するとき（郵送しないとき）】',
        check('議会事務局の受付の日と時間を確かめた（平日の昼間が多い）'),
        check('陳情書と、手元に残す写しを持った'),
        check('窓口に出した（　　月　　日）'),
        '',
        '【4　出したあと】',
        check('1週間ほどしたら、議会事務局に、受け付けられたかと審査の日を聞いた'),
        check('審査の日：　　月　　日（できれば委員会を傍聴する）'),
        check('結果を確かめた（採択・不採択・継続など）'),
      );
    } else {
      L.push(
        '',
        '【2　出す】',
        check('自治体の公式サイトで、要望・意見の受け付け方（窓口・郵送・メール・フォーム）を確かめた'),
        check('その方法で出した（　　月　　日）'),
      );
    }
    if (o.councils.length) {
      L.push('', '【出す先ごとのこと】');
      o.councils.forEach((c) => {
        L.push('', `■ ${c.name}`);
        if (!request) L.push(`・郵送：${c.mail || '郵送で審査されるかは分かっていません（審査まで確実にしたいときは電話で聞く）'}`);
        if (c.denshi) L.push('・電子申請でも出せるようです。');
        if (!request && c.sessions) L.push(`・定例会：${c.sessions}月（開会日は議会の日程で確かめ、その3週間前までに届くように出す）`);
        if (c.deadline) L.push(`・締切：「${c.deadline}」`);
        if (c.tel) L.push(`・電話：${c.tel}`);
        if (c.address) L.push(`・住所：${c.address}`);
        if (c.access) L.push(`・持参：${c.access}`);
        if (c.stamp && !request) L.push(`・切手の目安（角2封筒・定形外郵便）：${c.stamp}`);
        if (c.page) L.push(`・案内ページ：${c.page}`);
      });
    }
    return L.join('\n');
  }
  return { build };
})();
